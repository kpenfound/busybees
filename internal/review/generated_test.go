// section is one file's part of a diff for these tests: a header and one
// hunk with the lines given, "+" and "-" ones counted by the code under
// test.
func section(oldPath, newPath string, lines ...string) string {
	name := newPath
	if name == "" {
		name = oldPath
	}
	var out strings.Builder
	out.WriteString("diff --git a/" + name + " b/" + name + "\n")
	switch {
	case oldPath == "":
		out.WriteString("new file mode 100644\n--- /dev/null\n+++ b/" + newPath + "\n")
	case newPath == "":
		out.WriteString("deleted file mode 100644\n--- a/" + oldPath + "\n+++ /dev/null\n")
	default:
		out.WriteString("--- a/" + oldPath + "\n+++ b/" + newPath + "\n")
	}
	out.WriteString("@@ -1,2 +1,2 @@\n")
	for _, l := range lines {
		out.WriteString(l + "\n")
	}
	return out.String()
}

const generatedLine = "// Code generated by protoc-gen-go. DO NOT EDIT."

func TestSplitDiffNamesEachFileAndCountsItsLines(t *testing.T) {
	diff := section("widget.go", "widget.go", " package widget", "-func Old() {}", "+func New() {}", "+func Newer() {}") +
		section("", "added.go", "+package added") +
		section("gone.go", "", "-"+generatedLine, "-package gone") +
		"diff --git a/old name.go b/new name.go\nsimilarity index 100%\nrename from old name.go\nrename to new name.go\n" +
		"diff --git a/img.png b/img.png\nBinary files a/img.png and b/img.png differ\n"
	got := splitDiff(diff)
	type want struct {
		oldPath, newPath string
		added, removed   int
	}
	wants := []want{
		{"widget.go", "widget.go", 2, 1},
		{"", "added.go", 1, 0},
		{"gone.go", "", 0, 2},
		{"old name.go", "new name.go", 0, 0},
		{"img.png", "img.png", 0, 0},
	}
	if len(got) != len(wants) {
		t.Fatalf("%d sections, want %d: %+v", len(got), len(wants), got)
	}
	for i, w := range wants {
		s := got[i]
		if s.oldPath != w.oldPath || s.newPath != w.newPath || s.added != w.added || s.removed != w.removed {
			t.Errorf("section %d = %q -> %q +%d -%d, want %q -> %q +%d -%d", i, s.oldPath, s.newPath, s.added, s.removed, w.oldPath, w.newPath, w.added, w.removed)
		}
	}
	if got[2].removedLines[0] != generatedLine {
		t.Errorf("a deleted file's removed lines %q, want its old head", got[2].removedLines)
	}
	if joined := got[0].text + got[1].text + got[2].text + got[3].text + got[4].text; joined != diff {
		t.Errorf("the sections do not add up to the diff:\n%s", joined)
	}
}

func TestMatchGenerated(t *testing.T) {
	cases := []struct {
		pattern, path string
		match         bool
	}{
		{"*.pb.go", "api/v1/widget.pb.go", true},
		{"*.pb.go", "api/v1/widget.go", false},
		{"vendor", "vendor/acme/lib.go", true},
		{"vendor/", "vendor/acme/lib.go", true},
		{"vendor/*", "vendor/acme/lib.go", true},
		{"vendor/*.go", "vendor/acme/lib.go", false},
		{"gen/**/*.ts", "gen/a/b/c.ts", true},
		{"gen/**/*.ts", "gen/c.ts", true},
		{"gen/**/*.ts", "src/gen/c.ts", false},
		{"docs/api.md", "docs/api.md", true},
		{"docs/api.md", "docs/api.md.bak", false},
		{"./docs/api.md", "./docs/api.md", true},
		{"", "anything.go", false},
	}
	for _, c := range cases {
		got := matchGenerated([]string{c.pattern}, c.path)
		if (got != "") != c.match {
			t.Errorf("matchGenerated(%q, %q) = %q, want match %v", c.pattern, c.path, got, c.match)
		}
	}
}

// checkoutWithGenerated is a checkout of a pull request's head: a hand
// file, a file with the generated header, one .gitattributes marks, one
// it unmarks, and one a pattern names, with CheckoutBaseRef set so the
// diff can be read from it too.
func checkoutWithGenerated(t *testing.T) string {
	t.Helper()
	dir := gitRepo(t, "")
	commitFile(t, dir, "base.txt", "base\n")
	runGit(t, dir, "update-ref", CheckoutBaseRef, "HEAD")
	commitFile(t, dir, ".gitattributes", "marked.go linguist-generated\nalso.go linguist-generated=true\nunmarked.go -linguist-generated\n")
	commitFile(t, dir, "widget.go", "package widget\n\nfunc Widget() {}\n")
	commitFile(t, dir, "widget.pb.go", "// Copyright\n\n"+generatedLine+"\n\npackage widget\n")
	commitFile(t, dir, "marked.go", "package widget\n")
	commitFile(t, dir, "also.go", "package widget\n")
	commitFile(t, dir, "unmarked.go", "package widget\n")
	commitFile(t, dir, "schema.sql", "create table widget();\n")
	return dir
}

func TestExcludeGeneratedTellsGeneratedFilesFromHandFilesInACheckout(t *testing.T) {
	dir := checkoutWithGenerated(t)
	diff := section("widget.go", "widget.go", "-func Old() {}", "+func Widget() {}") +
		section("", "widget.pb.go", "+// Copyright", "+", "+"+generatedLine, "+package widget") +
		section("", "marked.go", "+package widget") +
		section("", "also.go", "+package widget") +
		section("", "unmarked.go", "+package widget") +
		section("gone.pb.go", "", "-"+generatedLine, "-package gone", "-func Gone() {}") +
		section("", "schema.sql", "+create table widget();")
	filtered, excluded, partial := excludeGenerated(context.Background(), diff, dir, []string{"*.sql"})
	if partial != "" {
		t.Errorf("partial = %q, want a complete detection with a checkout", partial)
	}
	want := []ExcludedFile{
		{Path: "widget.pb.go", Added: 4, Reason: ReasonHeader},
		{Path: "marked.go", Added: 1, Reason: ReasonAttribute},
		{Path: "also.go", Added: 1, Reason: ReasonAttribute},
		{Path: "gone.pb.go", Removed: 3, Reason: ReasonHeader},
		{Path: "schema.sql", Added: 1, Reason: ReasonPattern + ": *.sql"},
	}
	if !reflect.DeepEqual(excluded, want) {
		t.Errorf("excluded %+v\nwant %+v", excluded, want)
	}
	if wantDiff := section("widget.go", "widget.go", "-func Old() {}", "+func Widget() {}") + section("", "unmarked.go", "+package widget"); filtered != wantDiff {
		t.Errorf("filtered diff:\n%s\nwant the hand files alone:\n%s", filtered, wantDiff)
	}
}

func TestWithoutACheckoutOnlyThePatternsAreCheckedAndTheReviewSaysSo(t *testing.T) {
	diff := section("widget.go", "widget.go", "+func Widget() {}") +
		section("", "widget.pb.go", "+"+generatedLine, "+package widget") +
		section("", "schema.sql", "+create table widget();")
	filtered, excluded, partial := excludeGenerated(context.Background(), diff, "", []string{"*.sql"})
	if !strings.Contains(partial, "no checkout") || !strings.Contains(partial, ".gitattributes") {
		t.Errorf("partial = %q, want the checks that were skipped named", partial)
	}
	if len(excluded) != 1 || excluded[0].Path != "schema.sql" {
		t.Errorf("excluded %+v, want the pattern's file alone", excluded)
	}
	if !strings.Contains(filtered, "widget.pb.go") || strings.Contains(filtered, "schema.sql") {
		t.Errorf("filtered diff:\n%s", filtered)
	}
	// A checkout that is not a git repository costs the attributes check,
	// not the review, and the header check still runs.
	filtered, excluded, partial = excludeGenerated(context.Background(), diff, t.TempDir(), nil)
	if !strings.Contains(partial, ".gitattributes of the checkout could not be read") {
		t.Errorf("partial = %q, want the attributes read failure", partial)
	}
	if len(excluded) != 0 || !strings.Contains(filtered, "schema.sql") {
		t.Errorf("excluded %+v with no checkout files to read", excluded)
	}
}

