func TestGeneratedPatternsAreValidated(t *testing.T) {
	p, err := ParseProject("generated = [\"*.pb.go\", \"vendor/**\"]\n", "/tmp/context.toml")
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(p.Generated, []string{"*.pb.go", "vendor/**"}) {
		t.Errorf("generated = %v", p.Generated)
	}
	_, err = ParseProject("generated = [\"\", \"/abs/*.go\", \"../*.go\", \"[\"]\n", "/tmp/context.toml")
	if err == nil {
		t.Fatal("bad patterns parsed")
	}
	for _, want := range []string{"generated[0] is empty", "generated[1] \"/abs/*.go\" must be relative", "generated[2] \"../*.go\" must stay inside", "generated[3] \"[\" is not a valid pattern"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q does not say %q", err, want)
		}
	}
	if _, err := ParseProject("generated = \"*.pb.go\"\n", "/tmp/context.toml"); err == nil {
		t.Error("a string where a list is wanted parsed")
	}
}

// A pull request touching a generated file and a hand file: the distiller
// and the angles see the hand file's diff alone, the brief names the
// generated file with its line counts, and a finding on it is dropped.
func TestARunReviewsTheHandFilesAndDropsFindingsOnTheGeneratedOnes(t *testing.T) {
	agent := &reviewAgent{answers: map[string]string{
		AngleGeneral: sessionAnswer(
			`{"category": "naming", "severity": "high", "file": "widget.pb.go", "lines": [2, 2], "side": "new", "title": "A name in the binding", "body": "generated"}`,
			`{"category": "naming", "severity": "medium", "file": "widget.go", "lines": [1, 1], "side": "new", "title": "Receiver names here are short", "body": "w"}`,
		),
	}}
	r, log := testRunner(t, agent, nil)
	// The machine's checkout is not the pull request's head, so the
	// generated file is told by a pattern; its header is checked from the
	// checkout the review makes, which this runner does not.
	writeFile(t, r.Pipeline.Dir, ProjectFile, "generated = [\"*.pb.go\"]\n[angles]\nquick_general = false\ndocs = false\nside_effects = false\n")
	project, err := LoadProject(FindProject(r.Pipeline.Dir))
	if err != nil {
		t.Fatal(err)
	}
	r.Pipeline.Project = project
	f := sampleGH()
	f.diff = section("widget.go", "widget.go", "+func Widget() {}") + section("", "widget.pb.go", "+"+generatedLine, "+package widget", "+var Generated = 1")
	r.Pipeline.Client = f.client(t)

	a, err := r.Run(context.Background(), Ref{Repo: testRepo, Number: 7})
	if err != nil {
		t.Fatal(err)
	}
	want := []ExcludedFile{{Path: "widget.pb.go", Added: 3, Reason: ReasonPattern + ": *.pb.go"}}
	if !reflect.DeepEqual(a.Brief.Excluded, want) {
		t.Errorf("brief.Excluded %+v, want %+v", a.Brief.Excluded, want)
	}
	if p := agent.reqs[DistillerName].Prompt; strings.Contains(p, "var Generated") || !strings.Contains(p, "+func Widget() {}") || !strings.Contains(p, "- widget.pb.go (+3 -0; generated in context.toml: *.pb.go)") {
		t.Errorf("the distiller was given the generated file's diff, or not told of it:\n%s", p)
	}
	if p := agent.reqs[AngleGeneral].Prompt; !strings.Contains(p, "## Generated files not reviewed\n") || !strings.Contains(p, "- widget.pb.go (+3 -0; generated in context.toml: *.pb.go)") {
		t.Errorf("the angle was not told of the generated file:\n%s", p)
	}
	if got := titles(a.Findings.Items); !reflect.DeepEqual(got, []string{"Widget has no test", "Receiver names here are short"}) {
		t.Errorf("findings %v, want the finding on the generated file dropped", got)
	}
	if !strings.Contains(log.String(), "  1 finding on generated files dropped\n") {
		t.Errorf("log:\n%s", log.String())
	}
	// Without the pull request's checkout, the brief says the detection
	// was partial.
	if !strings.Contains(strings.Join(a.Brief.NotGathered, "\n"), "generated files: no checkout") {
		t.Errorf("not gathered %v, want the partial detection", a.Brief.NotGathered)
	}
}

